-- PARTE 1: TABELA DE DADOS DO SITE (Para o painel administrativo e fotos)
create table if not exists mrj_site_data (
  id integer primary key,
  data jsonb not null,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table mrj_site_data enable row level security;

drop policy if exists "Permitir leitura pública do site" on mrj_site_data;
create policy "Permitir leitura pública do site"
on mrj_site_data for select
to anon, authenticated
using (true);

drop policy if exists "Permitir atualização do site pelo painel" on mrj_site_data;
create policy "Permitir atualização do site pelo painel"
on mrj_site_data for insert
to anon, authenticated
with check (true);

drop policy if exists "Permitir update do site pelo painel" on mrj_site_data;
create policy "Permitir update do site pelo painel"
on mrj_site_data for update
to anon, authenticated
using (true);

insert into mrj_site_data (id, data, updated_at)
values (1, '{}'::jsonb, now())
on conflict (id) do nothing;


-- ==============================================================================
-- PARTE 2: TABELA DE LEADS (Para quem clica para baixar os PDFs dos imóveis)
-- ==============================================================================
create table if not exists leads (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null,
  email text,
  project_id text,
  project_name text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table leads enable row level security;

-- Permitir que os visitantes do site enviem seus dados ao solicitar o PDF
drop policy if exists "Visitantes podem enviar leads" on leads;
create policy "Visitantes podem enviar leads"
on leads for insert
to anon, authenticated
with check (true);

-- Permitir que o painel administrativo leia a lista de leads capturados
drop policy if exists "Painel pode consultar leads" on leads;
create policy "Painel pode consultar leads"
on leads for select
to anon, authenticated
using (true);

